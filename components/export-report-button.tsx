"use client"

import { useState } from "react"
import { Button } from "@/components/ui/button"
import { Download, Check } from "lucide-react"
import type { AuditResult } from "@/lib/audit-engine"
import { generateFixSnippet } from "@/lib/audit-engine"
import { trackEvent } from "@/lib/analytics"
import { SNAPSHOT_SOURCE } from "@/lib/audit-snapshot"

export function ExportReportButton({ data, scope }: { data?: AuditResult; scope?: string }) {
  const [copied, setCopied] = useState(false)

  if (!data) return null

  const generateMarkdownReport = (): string => {
    const dateStr = new Date(data.runAt || Date.now()).toISOString().slice(0, 10)
    const failedChecks = data.checks.filter((c) => c.status === "failed")
    const scoreText = data.score === null ? "not scored" : `${data.score}/100`
    let md = `# Snowflake & dbt Audit Report\n\n`
    if (data.config.demo) {
      md += `> **RECORDED DEMO RUN** - a real audit of the public dbt project ${SNAPSHOT_SOURCE.project} (${SNAPSHOT_SOURCE.commit}), run on Snowflake on ${SNAPSHOT_SOURCE.recordedAt.slice(0, 10)} and replayed without querying Snowflake.\n`
      if (SNAPSHOT_SOURCE.seeded.length > 0) md += `> Defects added on purpose for the demo: ${SNAPSHOT_SOURCE.seeded.join("; ")}.\n`
      md += `\n`
    }
    md += `**Target Scope**: \`${data.config.database}.${data.config.schema}\` on Warehouse \`${data.config.warehouse}\`\n`
    md += `**Audit Date**: ${dateStr}\n`
    if (scope) md += `**Scope**: ${scope}\n`
    md += `**Overall Health Score**: **${scoreText}**\n\n`
    md += `---\n\n`

    md += `## 1. Executive Summary\n\n`
    md += `| Metric | Value |\n`
    md += `|---|---|\n`
    md += `| Total Models / Tables | **${data.totalModels}** |\n`
    md += `| Critical Bugs / Errors | **${data.errors}** |\n`
    md += `| Architectural Warnings | **${data.warnings}** |\n`
    md += `| Optimization Opportunities | **${data.infos}** |\n`
    md += `| Overall Health Score | **${scoreText}** |\n`
    md += `| Checks that could not run | **${failedChecks.length}** |\n\n`
    if (failedChecks.length > 0) {
      md += `**Checks that could not run** (their rules were NOT evaluated):\n\n`
      for (const c of failedChecks) md += `- \`${c.rule}\`: ${c.error ?? "unknown error"}\n`
      md += `\n`
    }

    md += `## 2. Prioritized Action Plan & 1-Click Code Fixes\n\n`
    if (data.findings.length === 0) {
      md += failedChecks.length > 0
        ? `*No findings from the checks that ran. ${failedChecks.length} check(s) could not run, so this is not a clean bill of health.*\n\n`
        : `*No findings from the ${data.checks.length} checks that ran.*\n\n`
    } else {
      md += `| Severity | Rule | Target Object | Impact & Details | Recommended Fix |\n`
      md += `|---|---|---|---|---|\n`
      for (const f of data.findings) {
        const sevEmoji = f.severity === "error" ? "🚨 Error" : f.severity === "warning" ? "⚠️ Warning" : "ℹ️ Info"
        const fixCode = f.fixSnippet || generateFixSnippet(f)
        const cleanFix = fixCode.replace(/\n/g, " ")
        md += `| ${sevEmoji} | \`${f.rule}\` | \`${f.model || "-"}\` | ${f.message}${f.detail ? ` (${f.detail})` : ""} | \`${cleanFix}\` |\n`
      }
      md += `\n`
    }

    md += `## 3. Detailed Remediation Code Snippets\n\n`
    for (const f of data.findings) {
      if (f.model) {
        const fixCode = f.fixSnippet || generateFixSnippet(f)
        md += `### Fix for \`${f.model}\` (${f.rule})\n`
        md += `\`\`\`sql\n${fixCode}\n\`\`\`\n\n`
      }
    }

    md += `## 4. Audited Models Inventory\n\n`
    if (data.models.length === 0) {
      md += `*No tables or views found in schema.*\n\n`
    } else {
      md += `| Object Name | Kind | Rows | Size (MB) | Last Altered | Clustering |\n`
      md += `|---|---|---|---|---|---|\n`
      for (const m of data.models) {
        const mb = (m.bytes / 1_000_000).toFixed(2)
        md += `| \`${m.name}\` | ${m.kind} | ${m.rows === null ? "view" : m.rows.toLocaleString()} | ${mb} MB | ${m.lastAltered || "-"} | ${m.clusterBy || "None"} |\n`
      }
      md += `\n`
    }

    md += `---\n`
    md += `*Generated by dbt-model-auditor from read-only Snowflake metadata.*\n`
    return md
  }

  const handleDownload = () => {
    const md = generateMarkdownReport()
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" })
    const url = URL.createObjectURL(blob)
    const a = document.createElement("a")
    a.href = url
    a.download = `audit-restitution-${data.config.database}-${data.config.schema}.md`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)

    setCopied(true)
    setTimeout(() => setCopied(false), 2500)
  }

  return (
    <Button
      variant="default"
      size="sm"
      onClick={() => {
        trackEvent("export_report")
        handleDownload()
      }}
      className="gap-2 bg-primary hover:bg-primary/90 text-white shadow-xs"
    >
      {copied ? <Check className="h-4 w-4" /> : <Download className="h-4 w-4" />}
      {copied ? "Exported!" : "Export Restitution (.md)"}
    </Button>
  )
}
