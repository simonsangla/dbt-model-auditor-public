import { describe, it, expect } from "vitest"
import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { GET, POST } from "../../app/api/trust/route"
import TRUST_SAMPLE_JSON from "../../lib/trust-sample.json"
import type { TrustReport } from "../../lib/trust-contract"

const TRUST_SAMPLE = TRUST_SAMPLE_JSON as TrustReport & { generated_by: string }
import { validateTrustReport } from "../../lib/trust-contract"

describe("trust sample fixture", () => {
  it("is generated by the toolkit, never hand-written (V12)", () => {
    expect(TRUST_SAMPLE.generated_by).toMatch(/^validation_harness\.py .*--json /)
    expect(existsSync(join(__dirname, "../../lib/trust-sample.ts"))).toBe(false)
    expect(readFileSync(join(__dirname, "../../app/api/trust/route.ts"), "utf8")).toContain("trust-sample.json")
  })

  it("is a valid recorded real run on the jaffle-shop inputs (5 metrics, 5 questions), seeded defects named", () => {
    const r = validateTrustReport(TRUST_SAMPLE)
    expect(r.ok).toBe(true)
    expect(TRUST_SAMPLE.synthetic).toBe(false)
    expect(TRUST_SAMPLE.generated_by).toContain("--snowflake-config")
    expect(TRUST_SAMPLE.source).toMatch(/seeded/)
    expect(TRUST_SAMPLE.metrics).toHaveLength(5)
    expect(TRUST_SAMPLE.questions).toHaveLength(5)
  })
})

describe("GET /api/trust", () => {
  it("returns the bundled recorded run, flagged demo and not synthetic (V3)", async () => {
    const res = await GET()
    expect(res.status).toBe(200)
    const body = await res.json()
    expect(body.demo).toBe(true)
    expect(body.synthetic).toBe(false)
    expect(body.passed + body.failed + body.warnings).toBe(5)
    expect(body.failed).toBe(1)
  })
})

describe("no warehouse access (V1)", () => {
  it.each(["app/api/trust/route.ts", "lib/trust-contract.ts"])("%s never imports snowflake or cortex", (file) => {
    const src = readFileSync(join(__dirname, "../..", file), "utf8")
    expect(src).not.toMatch(/from\s+["'][^"']*(lib\/snowflake|lib\/cortex|snowflake-sdk)/)
  })
})

describe("POST /api/trust", () => {
  const post = (body: string) =>
    POST(new Request("http://localhost:3107/api/trust", { method: "POST", body, headers: { "content-type": "application/json" } }))

  it("scores a valid uploaded report, not flagged demo", async () => {
    const res = await post(JSON.stringify({ ...TRUST_SAMPLE, synthetic: false, source: "client run" }))
    expect(res.status).toBe(200)
    const body = await res.json()
    expect(body.demo).toBe(false)
    expect(body.synthetic).toBe(false)
    expect(body.findings).toHaveLength(2)
  })

  it("returns 400 with errors for an invalid report (V2)", async () => {
    const res = await post(JSON.stringify({ schema_version: 9 }))
    expect(res.status).toBe(400)
    const body = await res.json()
    expect(body.errors.length).toBeGreaterThan(0)
    expect(body.findings).toBeUndefined()
  })

  it("returns 400 for malformed JSON (V2)", async () => {
    const res = await post("{not json")
    expect(res.status).toBe(400)
    expect((await res.json()).errors).toEqual(["body must be valid JSON"])
  })
})
